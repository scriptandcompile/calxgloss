/// Build the `invoke` function of the generated harness.
///
/// This is the only part that changes from one function under test to the
/// next, so it is written between two fixed chunks of harness code.
pub fn generate_invoke(spec: &HarnessSpec) -> Result<String> {
    let expected = spec.params.len();
    let mut out = String::new();

    // Buffers requested by pointer arguments must outlive the call into the
    // target function, so they are kept in one arena. The arena is only
    // emitted when a pointer is present, otherwise it would be unused.
    let has_pointer = spec
        .params
        .iter()
        .any(|p| p.kind == crate::wine::ScalarKind::Ptr);

    writeln!(
        out,
        "/// Call the function under test with the arguments supplied on the wire.\n\
         fn invoke(addr: usize, fields: &[&str]) -> Result<String, String> {{\n\
         \x20   if fields.len() != {expected} {{\n\
         \x20       return Err(format!(\"expected {expected} arguments, got {{}}\", fields.len()));\n\
         \x20   }}"
    )
    .expect("writing to a String cannot fail");

    if has_pointer {
        writeln!(
            out,
            "    // Buffers requested by pointer arguments must outlive the call, so they\n\
             \x20   // are held here rather than in the argument bindings.\n\
             \x20   let mut arena: Vec<Vec<u8>> = Vec::new();"
        )
        .expect("writing to a String cannot fail");
    }

    for (i, p) in spec.params.iter().enumerate() {
        let tag = p.kind.tag();
        let parse = match p.kind {
            crate::wine::ScalarKind::I8 => "as_i8",
            crate::wine::ScalarKind::I16 => "as_i16",
            crate::wine::ScalarKind::I32 => "as_i32",
            crate::wine::ScalarKind::I64 => "as_i64",
            crate::wine::ScalarKind::U8 => "as_u8",
            crate::wine::ScalarKind::U16 => "as_u16",
            crate::wine::ScalarKind::U32 => "as_u32",
            crate::wine::ScalarKind::U64 => "as_u64",
            crate::wine::ScalarKind::F32 => "as_f32",
            crate::wine::ScalarKind::F64 => "as_f64",
            crate::wine::ScalarKind::Unit => "as_void",
            // A pointer may name an address or request an allocation; either way
            // it is reinterpreted as the declared pointer type, so `*mut i8` and
            // `*const u16` both work.
            crate::wine::ScalarKind::Ptr => {
                writeln!(
                    out,
                    "    let a{i} = ptr_arg(fields[{i}], \"{tag}\", &mut arena)? as {ty};",
                    ty = p.rust_type
                )
                .expect("writing to a String cannot fail");
                continue;
            }
        };
        writeln!(
            out,
            "    let a{i} = {parse}(field(fields[{i}], \"{tag}\")?)?;"
        )
        .expect("writing to a String cannot fail");
    }

    let arg_list = (0..expected)
        .map(|i| format!("a{i}"))
        .collect::<Vec<_>>()
        .join(", ");

    writeln!(
        out,
        "    type TargetFn = {};\n\
         \x20   let func: TargetFn = unsafe {{ std::mem::transmute(addr) }};",
        spec.fn_pointer_type()
    )
    .expect("writing to a String cannot fail");

    match spec.return_kind {
        crate::wine::ScalarKind::Unit => {
            writeln!(out, "    func({arg_list});").expect("writing to a String cannot fail");
            writeln!(out, "    Ok(String::new())").expect("writing to a String cannot fail");
        }
        kind => {
            writeln!(out, "    let r = func({arg_list});")
                .expect("writing to a String cannot fail");
            let rendered = match kind {
                crate::wine::ScalarKind::F32 => "format!(\"f32:0x{:08x}\", r.to_bits())".to_string(),
                crate::wine::ScalarKind::F64 => "format!(\"f64:0x{:016x}\", r.to_bits())".to_string(),
                crate::wine::ScalarKind::Ptr => {
                    "if r.is_null() { \"p:null\".to_string() } else { format!(\"p:0x{:x}\", r as usize) }"
                        .to_string()
                }
                // Integers are sent as decimal text. `{r}` captures the binding,
                // so no positional argument is passed.
                _ => format!("format!(\"{}:{{r}}\")", kind.tag()),
            };
            writeln!(out, "    Ok({rendered})").expect("writing to a String cannot fail");
        }
    }

    writeln!(out, "}}\n").expect("writing to a String cannot fail");
    Ok(out)
}

