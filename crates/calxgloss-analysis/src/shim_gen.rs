/// Collects the set of crate root dependencies needed by the shim.
///
/// For known crates (wgpu, cpal, fmod-rs, vb6runtime), the crate root
/// is returned. For unknown crates, the crate root is `"{{ crate_name }}"`
/// as a placeholder.
fn collect_crate_deps(shim: &ShimLayer) -> Vec<String> {
    let crate_root = shim_crate_root(&shim.target_crate);
    if shim.mappings.is_empty() {
        return Vec::new();
    }
    vec![format!("use {crate_root};")]
}

fn shim_crate_root(crate_name: &str) -> String {
    // Known crates have their official crate name as the dependency.
    // Unknown crates are referenced by name (to be filled in during manual review).
    match crate_name {
        "wgpu" => "wgpu",
        "tiny-skia" => "tiny_skia",
        "cpal" => "cpal",
        "fmod-rs" => "fmod_rs",
        "vb6runtime" => "vb6runtime",
        _ => crate_name,
    }
    .to_string()
}

fn append_use_declarations(output: &mut String, shim: &ShimLayer) {
    let deps = collect_crate_deps(shim);
    if deps.is_empty() {
        return;
    }

    for dep in &deps {
        output.push_str(dep);
        output.push('\n');
    }
}

