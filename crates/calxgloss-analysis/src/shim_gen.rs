//! Shim source code generation.
//!
//! This module generates Rust source code for shim layers from a
//! [`calxgloss_types::ShimLayer`] mapping table. Each shim layer bridges
//! a Windows DLL's exported API surface to a target Rust crate's API.
//!
//! # Flow
//!
//! 1. After [`super::shim::generate_shim_mappings`] produces a [`ShimLayer`],
//!    call [`generate_shim_source`] to produce the Rust source code.
//! 2. The generated code is written to `re/shims/<dll_name>/shim.rs`.
//! 3. Downstream steps (test generation, verification) consume the source file.
//!
//! # Generated Code Structure
//!
//! The output is a complete Rust module containing:
//! - A module-level state struct (if mappings require shared resources)
//! - One exported `unsafe` function per mapping, routing to the target crate
//! - Inline comments documenting each mapping's parameter transforms
//! - `TODO` placeholders for mappings requiring non-trivial return conversion

use calxgloss_types::{ComplexityScore, ReturnMapping, ShimApiMapping, ShimLayer};

/// Configuration controlling how aggressively the generator fills in
/// stubs versus leaving `TODO` markers for manual review.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ShimGenerationMode {
    /// Generate complete, compilable code where possible. Leave `TODO` only
    /// for mappings that require significant manual work (e.g. complex type
    /// conversions or multi-step API sequences).
    Complete,

    /// Generate skeletal stubs for all mappings, with clear `TODO` comments
    /// explaining what each function needs to implement. Useful for getting
    /// the overall structure right before filling in details.
    Skeletal,
}

impl Default for ShimGenerationMode {
    fn default() -> Self {
        Self::Complete
    }
}

/// Generates Rust source code for a shim layer.
///
/// Given a [`ShimLayer`] with its API mappings, produces a complete Rust
/// source file as a string. The generated code implements every exported
/// function from the original DLL, routing calls to the equivalent target
/// crate API.
///
/// # Arguments
///
/// * `shim` — The shim layer containing DLL name, target crate, and mappings.
/// * `mode` — Generation mode controlling stub completeness.
///
/// # Generated Code
///
/// The output includes:
/// - Module doc comments with provenance (source DLL, target crate, mapping count)
/// - Crate dependency imports derived from the target crate name
/// - A `ShimState` struct if any mapping requires shared resource tracking
/// - One `pub unsafe fn` per mapping, with parameter transforms documented
///   in inline comments
///
/// # Example
///
/// ```no_run
/// use calxgloss_types::ShimLayer;
/// use calxgloss_analysis::shim_gen::{generate_shim_source, ShimGenerationMode};
///
/// # let shim = ShimLayer::new("d3d9.dll".to_string(), "wgpu".to_string());
/// let source = generate_shim_source(&shim, ShimGenerationMode::Skeletal);
/// ```
pub fn generate_shim_source(shim: &ShimLayer, mode: ShimGenerationMode) -> String {
    let mut output = String::new();

    // Module-level doc comment.
    append_doc_header(&mut output, shim);

    // Blank line after doc comments.
    if !output.ends_with('\n') {
        output.push('\n');
    }
    output.push_str("\n");

    // Use declarations for the target crate.
    append_use_declarations(&mut output, shim);

    output.push('\n');

    // Module-level state (if needed).
    if needs_state(shim) {
        append_state_struct(&mut output, shim);
        output.push('\n');
    }

    // Exported shim functions.
    append_shim_functions(&mut output, shim, &mode);

    output
}

// ============================================================
// Doc header
// ============================================================

fn append_doc_header(output: &mut String, shim: &ShimLayer) {
    let comment = format!(
        "//! Auto-generated shim layer for `{src_dll}`.\n\
         //!\n\
         //! This module translates calls from the original `{src_dll}` API surface\n\
         //! into equivalent calls on the `{crate_name}` crate. It is generated by\n\
         //! the Calxgloss reverse engineering harness and should not be edited by hand.\n\
         //!\n\
         //! Every exported function from the original DLL is implemented here, routing\n\
         //! through the corresponding `{crate_name}` API.\n\
         //!\n\
         //! **Source:** `{src_dll}`\n\
         //! **Target crate:** `{crate_name}`\n\
         //! **Mappings:** {count}",
        src_dll = shim.source_dll,
        crate_name = shim.target_crate,
        count = shim.mapping_count(),
    );
    output.push_str(&comment);
    output.push('\n');
}

