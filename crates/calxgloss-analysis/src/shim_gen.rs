    #[test]
    fn test_generated_code_structure() {
        let mut shim = ShimLayer::new("test.dll".to_string(), "wgpu".to_string());
        shim.add_mapping(ShimApiMapping {
            original_api: "TestFunc".to_string(),
            original_params: vec!["UINT a".to_string(), "LPVOID b".to_string()],
            crate_api: "wgpu::test_func".to_string(),
            crate_params: vec!["u32".to_string()],
            parameter_transforms: vec!["a -> direct cast".to_string()],
            return_mapping: ReturnMapping::Void,
            complexity: ComplexityScore::Low,
            notes: "Test mapping".to_string(),
        });

        let source = generate_shim_source(&shim, ShimGenerationMode::Complete);

        // Check structure: doc -> use -> functions.
        assert!(source.starts_with("//!"));
        assert!(source.contains("use "));
        assert!(source.contains("unsafe fn test_func"));
        assert!(source.contains("wgpu::test_func"));
        assert!(source.contains("Transform: a -> direct cast"));
    }

